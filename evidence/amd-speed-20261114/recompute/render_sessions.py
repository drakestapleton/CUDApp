#!/usr/bin/env python3
# Write the two card-session tables of REPORT.md section 12 from out/sessions-table.json (between the two marker lines).
# REPORT.md is rewritten only if its bytes would change.
import json, sys
from common import HERE, OUT

rep = HERE.parent / 'REPORT.md'
rows = json.loads((OUT / 'sessions-table.json').read_text())
BEGIN, END = '<!-- sessions:begin (generated by recompute/render_sessions.py) -->', '<!-- sessions:end -->'
lines = [BEGIN,
         '| Session | UTC start | Lane | What ran | State |',
         '|---|---|---|---|---|']
for r in rows:
    lines.append(f"| {r['session'][-8:]} | {r['utc_start']} | {r['lane']} | {r['ran']} | {r['state']} |")
lines += ['', 'Evidence file and hash for each session (full session name; paths under `raw/`):', '',
          '| Session | Evidence | sha256 |', '|---|---|---|']
for r in rows:
    h = f"`{r['sha256']}`" if r['sha256'] else 'not downloaded'
    lines.append(f"| `{r['session']}` | `{r['evidence']}` | {h} |")
lines.append(END)
text = rep.read_text()
if BEGIN not in text or END not in text:
    sys.exit('RENDER FAIL: markers missing in REPORT.md')
head, rest = text.split(BEGIN, 1)
tail = rest.split(END, 1)[1]
new = head + '\n'.join(lines) + tail
if new != text:
    rep.write_text(new)
print(f'RENDER sessions rows={len(rows)} {"unchanged" if new == text else "written"}')
