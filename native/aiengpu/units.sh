#!/bin/sh
# SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception
# Regenerate the hosted aien-gpu effects unit (native/aiengpu/effects.om) through the bridge's context mode.
#
#   native/aiengpu/units.sh                 pinned: bridge revision and hashes from src/cudapp_aiengpu_effects.ident,
#                                           output into src/ (the committed generated C)
#   native/aiengpu/units.sh --adopt         take the bridge checkout's revision as the new pin (the checkout must be
#                                           clean): output into src/ with that revision and its hashes in the .ident
#   native/aiengpu/units.sh --candidate D [F]  any bridge checkout, revision and hashes recorded as candidate: output
#                                           into D only, never src/; F replaces effects.om (mutants, reproducibility)
# AArch64 only: the device-word compiler (omega-mv#1047, omc sha256 b8f8f137...) carries the aien-gpu 'A' devctl
# allowlist for aarch64linux; there is no x86 aien-gpu target.
set -eu
ROOT=$(CDPATH= cd -- "$(dirname "$0")/../.." && pwd)
BRIDGE=${OMEGA_AIENGPU_BRIDGE:?set OMEGA_AIENGPU_BRIDGE to the hosted/context bridge with the aien-gpu mapping profile}
OMC=${OMEGA_NATIVE_OMC:?set OMEGA_NATIVE_OMC to the native generator compiler}
ARM=${OMEGA_NATIVE_OMC2:?set OMEGA_NATIVE_OMC2 to the AArch64 context compiler with the aien-gpu devctl words}
GEN_PIN=734f0a39319fbfa930bcc62cb30dbf06d47d78e126372b74f5baf478e6126b61
ARM_PIN=b8f8f1371bc0303f8da02db8b754e085d5dd852620c8d8d676c5769c233d9195
SRC=native/aiengpu/effects.om
SRCFILE=$ROOT/$SRC
hash() { sha256sum < "$1" | cut -d' ' -f1; }
require_hash() {
    [ -n "$2" ] && [ "$(hash "$1")" = "$2" ] || { echo "NOT_RUN: aien-gpu effects pin mismatch: $1" >&2; exit 3; }
}
DEST=$ROOT/src
if [ "${1:-}" = "--candidate" ]; then
    DEST=${2:?--candidate needs an output directory}
    if [ -n "${3:-}" ]; then SRCFILE=$(CDPATH= cd -- "$(dirname "$3")" && pwd)/$(basename "$3"); SRC=$3; fi
    mkdir -p "$DEST"
    case $(CDPATH= cd -- "$DEST" && pwd) in
        "$ROOT/src" | "$ROOT"/src/*) echo "units.sh: a candidate never writes into src/" >&2; exit 2 ;;
    esac
    bridge_pin=candidate-$(git -C "$BRIDGE" rev-parse HEAD 2>/dev/null || echo unrevisioned)
    native_pin=$(hash "$BRIDGE/src/native.om")
    tool_pin=$(hash "$BRIDGE/tools/native")
elif [ "${1:-}" = "--adopt" ]; then
    [ -z "$(git -C "$BRIDGE" status --porcelain)" ] || { echo "units.sh: --adopt needs a clean bridge checkout" >&2; exit 2; }
    bridge_pin=$(git -C "$BRIDGE" rev-parse HEAD)
    native_pin=$(hash "$BRIDGE/src/native.om")
    tool_pin=$(hash "$BRIDGE/tools/native")
else
    IDENT=$ROOT/src/cudapp_aiengpu_effects.ident
    [ -f "$IDENT" ] || { echo "NOT_RUN: no pinned aien-gpu bridge yet ($IDENT); use --candidate" >&2; exit 3; }
    bridge_pin= native_pin= tool_pin=
    set -f
    for field in $(cat "$IDENT"); do
        case "$field" in
            bridge=*) bridge_pin=${field#bridge=} ;;
            bridge_native=*) native_pin=${field#bridge_native=} ;;
            bridge_tool=*) tool_pin=${field#bridge_tool=} ;;
        esac
    done
    set +f
    [ -n "$bridge_pin" ] && [ "$(git -C "$BRIDGE" rev-parse HEAD)" = "$bridge_pin" ] || {
        echo "NOT_RUN: aien-gpu effects bridge revision mismatch" >&2; exit 3;
    }
    require_hash "$BRIDGE/src/native.om" "$native_pin"
    require_hash "$BRIDGE/tools/native" "$tool_pin"
fi
require_hash "$OMC" "$GEN_PIN"
require_hash "$ARM" "$ARM_PIN"
case $(uname -m) in
    aarch64) ARM_CC=${OMEGA_AIENGPU_CC_AARCH64:-cc} ;;
    x86_64) ARM_CC=${OMEGA_AIENGPU_CC_AARCH64:-aarch64-linux-gnu-gcc} ;;
    *) echo "NOT_RUN: aien-gpu effects generation needs Linux AArch64 or an AArch64 cross compiler" >&2; exit 3 ;;
esac
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
export OMEGA_NATIVE_OMC OMEGA_NATIVE_OMC2
CC="$ARM_CC" "$BRIDGE/tools/native" --host --target aarch64linux "$T/arm" "$SRCFILE"
{
    printf '/* SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception */\n/* Generated by native/aiengpu/units.sh; do not edit. */\n#if defined(__aarch64__)\n'
    cat "$T/arm/omega_native.c"
    printf '\n#else\n#error "the aien-gpu effects are generated for Linux AArch64 only"\n#endif\n'
} > "$T/cudapp_aiengpu_effects.c"
{
    printf '/* SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception */\n/* Generated by native/aiengpu/units.sh; do not edit. */\n#ifndef CUDAPP_AIENGPU_NATIVE_H\n#define CUDAPP_AIENGPU_NATIVE_H\n#if defined(__aarch64__)\n'
    cat "$T/arm/omega_native.h"
    printf '\n#else\n#error "the aien-gpu effects are generated for Linux AArch64 only"\n#endif\n#endif\n'
} > "$T/cudapp_aiengpu_native.h"
printf '%s\n' "omega-native-ident 1 unit=aiengpu_effects path=$SRC bridge=$bridge_pin bridge_native=$native_pin bridge_tool=$tool_pin omc_generator=$GEN_PIN omc_aarch64=$ARM_PIN src=$(hash "$SRCFILE") c=$(hash "$T/cudapp_aiengpu_effects.c") h=$(hash "$T/cudapp_aiengpu_native.h")" > "$T/cudapp_aiengpu_effects.ident"
mkdir -p "$DEST"
cp "$T/cudapp_aiengpu_effects.c" "$T/cudapp_aiengpu_native.h" "$T/cudapp_aiengpu_effects.ident" "$DEST/"
printf 'AIEN-GPU EFFECTS GENERATION PASS (%s, AArch64, omc %.8s, bridge %s)\n' "$DEST" "$ARM_PIN" "$bridge_pin"
