#!/bin/sh
# SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception
# Regenerate both hosted instruction streams; portable wire units use om/units.sh.
set -eu
ROOT=$(CDPATH= cd -- "$(dirname "$0")/../.." && pwd)
BRIDGE=${OMEGA_NVRM_BRIDGE:?set OMEGA_NVRM_BRIDGE to the pinned hosted/context bridge}
OMC=${OMEGA_NATIVE_OMC:?set OMEGA_NATIVE_OMC to the native generator compiler}
ARM=${OMEGA_NATIVE_OMC2:?set OMEGA_NATIVE_OMC2 to the AArch64 context compiler}
X86=${OMEGA_NATIVE_X86_OMC:?set OMEGA_NATIVE_X86_OMC to the hosted x86 compiler}
GEN_PIN=734f0a39319fbfa930bcc62cb30dbf06d47d78e126372b74f5baf478e6126b61
ARM_PIN=d1a3047153e14676c4baf9248fa2b88bb1b68c37cfeb71d76f30f5230c7d2765
X86_PIN=cf4fcbbb4752c5dd0652b426c0f2d08f82e380e8fc6f5114acf51a4c077bb579
IDENT=$ROOT/src/cudapp_om_nvrm_transport.ident
bridge_pin= native_pin= tool_pin=
set -f
for field in $(cat "$IDENT"); do
    case "$field" in
        bridge=*) bridge_pin=${field#bridge=} ;;
        bridge_native=*) native_pin=${field#bridge_native=} ;;
        bridge_tool=*) tool_pin=${field#bridge_tool=} ;;
    esac
done
set +f
hash() { sha256sum < "$1" | cut -d' ' -f1; }
require_hash() {
    [ -n "$2" ] && [ "$(hash "$1")" = "$2" ] || {
        echo "NOT_RUN: native NVRM pin mismatch: $1" >&2; exit 3;
    }
}
[ -n "$bridge_pin" ] && [ "$(git -C "$BRIDGE" rev-parse HEAD)" = "$bridge_pin" ] || {
    echo "NOT_RUN: native NVRM bridge revision mismatch" >&2; exit 3;
}
require_hash "$BRIDGE/src/native.om" "$native_pin"
require_hash "$BRIDGE/tools/native" "$tool_pin"
require_hash "$OMC" "$GEN_PIN"
require_hash "$ARM" "$ARM_PIN"
require_hash "$X86" "$X86_PIN"
case $(uname -m) in
    aarch64) ARM_CC=${OMEGA_NVRM_CC_AARCH64:-cc}; X86_CC=${OMEGA_NVRM_CC_X86:-x86_64-linux-gnu-gcc} ;;
    x86_64) ARM_CC=${OMEGA_NVRM_CC_AARCH64:-aarch64-linux-gnu-gcc}; X86_CC=${OMEGA_NVRM_CC_X86:-cc} ;;
    *) echo "NOT_RUN: native NVRM generation needs Linux AArch64/x86-64 cross compilers" >&2; exit 3 ;;
esac
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
export OMEGA_NATIVE_OMC OMEGA_NATIVE_OMC2 OMEGA_NATIVE_X86_OMC
CC="$ARM_CC" "$BRIDGE/tools/native" --host --target aarch64linux "$T/arm" "$ROOT/native/nvrm/transport.om" "$ROOT/native/streams/submit.om"
CC="$X86_CC" "$BRIDGE/tools/native" --host --target x86linux "$T/x86" "$ROOT/native/nvrm/transport.om" "$ROOT/native/streams/submit.om"
{
    printf '/* SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception */\n/* Generated by native/nvrm/units.sh; do not edit. */\n#if defined(__aarch64__)\n'
    cat "$T/arm/omega_native.c"
    printf '\n#elif defined(__x86_64__)\n'
    cat "$T/x86/omega_native.c"
    printf '\n#else\n#error "NVRM hosted transport requires Linux AArch64 or x86-64"\n#endif\n'
} > "$T/cudapp_om_nvrm_transport.c"
{
    printf '/* SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception */\n/* Generated by native/nvrm/units.sh; do not edit. */\n#ifndef CUDAPP_NVRM_NATIVE_H\n#define CUDAPP_NVRM_NATIVE_H\n#if defined(__aarch64__)\n'
    cat "$T/arm/omega_native.h"
    printf '\n#elif defined(__x86_64__)\n'
    cat "$T/x86/omega_native.h"
    printf '\n#else\n#error "NVRM hosted transport requires Linux AArch64 or x86-64"\n#endif\n#endif\n'
} > "$T/cudapp_nvrm_native.h"
printf '%s\n' "omega-native-ident 1 unit=nvrm_transport path=native/nvrm/transport.om+native/streams/submit.om bridge=$bridge_pin bridge_native=$native_pin bridge_tool=$tool_pin omc_generator=$GEN_PIN omc_aarch64=$ARM_PIN omc_x86=$X86_PIN src=$(cat "$ROOT/native/nvrm/transport.om" "$ROOT/native/streams/submit.om" | sha256sum | cut -d" " -f1) c=$(hash "$T/cudapp_om_nvrm_transport.c") h=$(hash "$T/cudapp_nvrm_native.h")" > "$T/cudapp_om_nvrm_transport.ident"
cp "$T/cudapp_om_nvrm_transport.c" "$T/cudapp_nvrm_native.h" "$T/cudapp_om_nvrm_transport.ident" "$ROOT/src/"
printf 'NVRM NATIVE GENERATION PASS (AArch64+x86-64, pinned context compilers and bridge)\n'
