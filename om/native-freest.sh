# Regenerate src/cudapp_freest_pathcopy.c from om/components/pathcopy.om.
# The committed .c is the artifact. This script is the regeneration path, not a build step.
# AArch64 and x86-64 halves are selected by the compiler; only one is compiled.
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
OMC_PIN=734f0a39319fbfa930bcc62cb30dbf06d47d78e126372b74f5baf478e6126b61
OMC2_PIN=2c82480596bbdc50cda9626866209ef662d5834f278f839ff4ce0250c495029f
X86_PIN=be8c51301307555254fc59e351d281aae1aa096d91521777e33a41c8b446448a
NATIVE_PIN=a08c7718633de766b8a8690dccd3809fe152b14c2c31a9f84bacf307b41c9721
UNIT=${PATHCOPY_UNIT:-$ROOT/om/components/pathcopy.om}
DEST=${PATHCOPY_DEST:-$ROOT/src/cudapp_freest_pathcopy.c}
BRIDGE=${OMEGA_BRIDGE:?set OMEGA_BRIDGE to a checkout of omega-bridge #72}
OMC=${OMEGA_NATIVE_OMC:?set OMEGA_NATIVE_OMC to the #72 generator omc}
OMC2=${OMEGA_NATIVE_OMC2:?set OMEGA_NATIVE_OMC2 to the OM-2 compiler e5b32567}
X86=${OMEGA_NATIVE_X86_OMC:?set OMEGA_NATIVE_X86_OMC to the x86 OM-2 compiler}
[ "$(sha256sum < "$OMC" | cut -c1-64)" = "$OMC_PIN" ] || { echo "NOT_RUN: generator omc is not the #72 pin"; exit 3; }
[ "$(sha256sum < "$OMC2" | cut -c1-64)" = "$OMC2_PIN" ] || { echo "NOT_RUN: OM-2 omc is not e5b32567"; exit 3; }
[ "$(sha256sum < "$X86" | cut -c1-64)" = "$X86_PIN" ] || { echo "NOT_RUN: x86 omc is not the #72 pin"; exit 3; }
[ "$(sha256sum < "$BRIDGE/tools/native" | cut -c1-64)" = "$NATIVE_PIN" ] || { echo "NOT_RUN: tools/native is not the #72 frontend"; exit 3; }
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
mkdir -p "$T/a64" "$T/x86"
export OMEGA_NATIVE_OMC="$OMC" OMEGA_NATIVE_OMC2="$OMC2" OMEGA_NATIVE_X86_OMC="$X86"
if [ "${PATHCOPY_ARCH:-both}" = both ] || [ "${PATHCOPY_ARCH:-both}" = a64 ]; then
  CC=aarch64-linux-gnu-gcc sh "$BRIDGE/tools/native" --freestanding --target aarch64linux "$T/a64" "$UNIT"
fi
if [ "${PATHCOPY_ARCH:-both}" = both ] || [ "${PATHCOPY_ARCH:-both}" = x86 ]; then
  CC=x86_64-linux-gnu-gcc sh "$BRIDGE/tools/native" --freestanding --target x86linux "$T/x86" "$UNIT"
fi

{
  printf '%s\n' '/* Generated by om/native-freest.sh from om/components/pathcopy.om.'
  printf '%s\n' ' * omega-bridge tools/native --freestanding (draft #72). Do not edit.'
  printf '%s\n' ' * AArch64 and x86-64 only. The unused half is not compiled. */'
printf '%s\n' '#if defined(__aarch64__)'
if [ -f "$T/a64/omega_native.c" ]; then cat "$T/a64/omega_native.c"; else printf '%s\n' '#error pathcopy aarch64 half was not generated'; fi
printf '%s\n' '#elif defined(__x86_64__)'
if [ -f "$T/x86/omega_native.c" ]; then cat "$T/x86/omega_native.c"; else printf '%s\n' '#error pathcopy x86-64 half was not generated'; fi
  printf '%s\n' '#else'
  printf '%s\n' '#error pathcopy freestanding binding is aarch64 or x86-64 only'
  printf '%s\n' '#endif'
} > "$DEST"
echo "WROTE $DEST"
