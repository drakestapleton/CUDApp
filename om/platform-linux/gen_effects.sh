# Regenerates om/platform-linux/gen/*.c from the platform .om units.
# Output is not src/cudapp_om_*.c: that glob is one link, and each generated
# runtime defines omega_native_context_create. Callers compile these with
# -D renames (mk/platform-linux.mk). Needs the retire-compiler pair and
# BridgeX86 tools/native. The pinned CUDApp omc rejects cpufence and mapget.
set -eu
ROOT=$(CDPATH= cd -- "$(dirname "$0")/../.." && pwd)
BRIDGE=${CUDAPP_EFFECTS_BRIDGE:-/home/drakestapleton/work/cudastack/lanes/BridgeX86}
X86_OMC=${OMEGA_NATIVE_X86_OMC:-/home/drakestapleton/work/cudastack/lanes/omega-mv-x86/seed/out/omc}
X86_CC=${OMEGA_NATIVE_X86_CC:-x86_64-linux-gnu-gcc}
OMC2=${OMEGA_NATIVE_OMC2:-/home/drakestapleton/work/cudastack/lanes/omega-mv-bh-retire/seed/out/omc}
OMC=${OMEGA_NATIVE_OMC:-/home/drakestapleton/work/cudastack/lanes/omega-mv-c6/seed/out/omc}
GEN="$ROOT/om/platform-linux/gen"
mkdir -p "$GEN"
export OMEGA_NATIVE_OMC2="$OMC2" OMEGA_NATIVE_OMC="$OMC" OMEGA_NATIVE_X86_OMC="$X86_OMC"
one() {
  name=$1
  src=$2
  T=$(mktemp -d)
  "$BRIDGE/tools/native" --host --target aarch64linux "$T/arm" "$src"
  CC="$X86_CC" "$BRIDGE/tools/native" --host --target x86linux "$T/x86" "$src"
  {
    printf '/* SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception */\n/* Generated by om/platform-linux/gen_effects.sh; do not edit. */\n#if defined(__aarch64__)\n'
    cat "$T/arm/omega_native.c"
    printf '\n#elif defined(__x86_64__)\n'
    cat "$T/x86/omega_native.c"
    printf '\n#else\n#error "platform omega units require Linux AArch64 or x86-64"\n#endif\n'
  } > "$GEN/$name.c"
  {
    printf '/* SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception */\n/* Generated by om/platform-linux/gen_effects.sh; do not edit. */\n#ifndef CUDAPP_PLAT_%s_H\n#define CUDAPP_PLAT_%s_H\n#include <stdint.h>\n#if defined(__aarch64__)\n' "$name" "$name"
    cat "$T/arm/omega_native.h"
    printf '\n#elif defined(__x86_64__)\n'
    cat "$T/x86/omega_native.h"
    printf '\n#else\n#error "platform omega units require Linux AArch64 or x86-64"\n#endif\n#endif\n'
  } > "$GEN/$name.h"
  rm -rf "$T"
}
one plat_effects "$ROOT/om/platform-linux/plat_effects.om"
one plat_wait "$ROOT/om/platform-linux/plat_wait.om"
# The carried test-platform-linux-wait mutant: the 2^31 deadline bound replaced by 0.
# Committed like the units above, so the gate compiles it without these compilers.
MT=$(mktemp -d)
grep -q 2147483648 "$ROOT/om/platform-linux/plat_wait.om"
sed 's/2147483648/0/' "$ROOT/om/platform-linux/plat_wait.om" > "$MT/plat_wait_mutant.om"
! grep -q 2147483648 "$MT/plat_wait_mutant.om"
one plat_wait_mutant "$MT/plat_wait_mutant.om"
rm -rf "$MT"
rename() {
  src=$1
  dst=$2
  p=$3
  # Symbols immediately following an escaped newline have no regex word boundary.
  sed -e "s/ombr_enter/${p}_ombr_enter/g" \
      -e "s/ombr_trap/${p}_ombr_trap/g" \
      -e "s/ombr_no_entry/${p}_ombr_no_entry/g" \
      -e "s/\\bomega_native_context_create\\b/${p}_context_create/g" \
      -e "s/\\bomega_native_context_destroy\\b/${p}_context_destroy/g" \
      "$src" > "$dst"
}
mkdir -p "$GEN/link"
rename "$GEN/plat_effects.c" "$GEN/link/plat_fx_effects.c" plat_fx
rename "$GEN/plat_wait.c" "$GEN/link/plat_fx_wait.c" plat_wt
echo "PASS platform effects generation"
