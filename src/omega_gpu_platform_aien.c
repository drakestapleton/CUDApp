/* One call of the unit. It is total over every argument this file passes, so a bridge status (trap, bad argument)
 * is a build defect, never a device answer: abort rather than guess. */
static uint64_t ag_call(AienReq *q, const uint64_t m[16]) {
    AienReq scratch;
    uint64_t res = 0;
    if (!q) { memset(&scratch, 0, sizeof scratch); q = &scratch; }
    const uint32_t s = omega_aiengpu(&res, m, 16, q->b, sizeof q->b);
    if (s != 0) {
        fprintf(stderr, "omega_aiengpu op %llu: bridge status %u\n", (unsigned long long)m[0], s);
        abort();
    }
    return res;
}
