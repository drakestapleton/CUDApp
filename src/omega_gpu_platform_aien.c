/* Every buffer lives in [64 GiB, 1 TiB): a GPFIFO entry carries 40 address bits (GET 31:2, GET_HI 39:32;
 * nvrm_gp_entry puts LEVEL at bit 41 and LENGTH at 42), and the kernel's own choice on arm64 is near 2^48. The
 * window is below AGPU_MEM_ALLOC's 2^48 limit and above GSP's [4 GiB, 4.5 GiB). */
#define AIEN_VA_BASE (64ull << 30)
#define AIEN_VA_TOP (1ull << 40)
#define AIEN_GP_MAX_WORDS 0x1fffffu /* LENGTH field, 21 bits */
/* omega #457: the same L2_SYSMEM_NCOH_INVALIDATE MEM_OP prefix as the Linux reference. */
static const uint32_t L2_INVAL_PREFIX[] = { (2u << 28) | (4u << 16) | (0x0028u >> 2), 0, 0, 0, 0x11u << 27 };
_Static_assert(sizeof L2_INVAL_PREFIX / sizeof L2_INVAL_PREFIX[0] == L2_INVAL_PREFIX_WORDS, "prefix length");

static int ag_info_check(AienReq *q) {
    return q->info.abi != AGPU_ABI_VERSION ? 1 : q->info.state != AGPU_STATE_RM_READY ? 2 : 0;
}
static uint64_t ag_mem_size(uint64_t bytes) {
    if (bytes == 0 || bytes > (1ull << 37)) return 0;
    return (bytes + AIEN_PAGE - 1u) & ~(AIEN_PAGE - 1u);
}
static uint64_t ag_va_start(uint64_t cursor) { return (cursor < AIEN_VA_BASE || cursor >= AIEN_VA_TOP) ? AIEN_VA_BASE : cursor; }
static uint64_t ag_va_align(uint64_t x, uint64_t align) {
    if (align < AIEN_PAGE) align = AIEN_PAGE;
    return (x + align - 1u) & ~(align - 1u);
}
static int ag_va_try(uint64_t at, uint64_t size, int wrapped, uint64_t start) {
    if (at + size > AIEN_VA_TOP) return wrapped ? VA_TRY_STOP : VA_TRY_WRAP;
    return (wrapped && at >= start) ? VA_TRY_STOP : VA_TRY_RESERVE;
}
static uint64_t ag_va_base(void) { return AIEN_VA_BASE; }
static uint64_t ag_va_top(void) { return AIEN_VA_TOP; }
static uint64_t ag_va_step(uint64_t at, uint64_t size, uint64_t align) { return ag_va_align(at + size, align); }
static void ag_req_alloc(AienReq *q, uint64_t size, uint64_t va, uint32_t flags) {
    memset(q, 0, sizeof *q);
    q->alloc.size = size; q->alloc.va = va; q->alloc.flags = flags;
}
static int ag_rm_ok(AienReq *q, uint32_t st_off) {
    struct agpu_rm_status st;
    memcpy(&st, q->b + st_off, sizeof st);
    return st.verdict == AGPU_RM_OK;
}
static void ag_req_free(AienReq *q, uint32_t handle) { memset(q, 0, sizeof *q); q->free.handle = handle; }
static void ag_req_chan(AienReq *q, uint32_t fifo, uint32_t notifier) {
    memset(q, 0, sizeof *q);
    q->chan.ring_handle = fifo;
    q->chan.entries = OMEGA_GPU_AIEN_GP_ENTRIES;
    q->chan.ring_off = 0;
    q->chan.userd_handle = fifo;
    q->chan.err_handle = notifier;
    q->chan.userd_off = OMEGA_GPU_AIEN_USERD_OFF;
}
static void ag_req_destroy(AienReq *q, uint32_t channel) { memset(q, 0, sizeof *q); q->destroy.channel = channel; }
/* The Linux reference's rule: GPU-cached only for device-private DATA buffers (no CPU_READ, no HOST_POLLED). */
static int ag_cache(uint32_t kind, uint32_t rights, uint32_t cache) {
    if (cache != OMEGA_GPU_CACHE_GPU_CACHED) return AGPU_MEM_GPU_UNCACHED;
    if (kind != OMEGA_GPU_HANDLE_BUF_DATA || (rights & (OMEGA_GPU_RIGHT_CPU_READ | OMEGA_GPU_RIGHT_HOST_POLLED))) return 2;
    return 0;
}
static int ag_range(uint64_t size, uint64_t off, uint64_t len) { return !(len == 0u || off > size || len > size - off); }
static int ag_poll(uint32_t rights, uint64_t off, uint64_t size) {
    if (!(rights & OMEGA_GPU_RIGHT_HOST_POLLED)) return POLL_RIGHTS;
    if (off & 3u) return POLL_ALIGN;
    return ag_range(size, off, 4u) ? POLL_OK : POLL_RANGE;
}
static int ag_serial_ge(uint32_t w, uint32_t target) { return (int32_t)(w - target) >= 0; }
uint64_t omega_gpu_aien_gp_entry(uint64_t va, uint32_t nwords) {
    return (va & ~3ull) | ((uint64_t)(nwords & AIEN_GP_MAX_WORDS) << 42) | (1ull << 41);
}
static int ag_submit(AienReq *plan, uint32_t nwords, int have_words, int pending, uint64_t pb_size, uint32_t put,
                     uint32_t retired, uint64_t pb_va) {
    if (!have_words || nwords == 0u) return SUBMIT_ARGS;
    const uint32_t pre = pending ? L2_INVAL_PREFIX_WORDS : 0u;
    const uint64_t total = (uint64_t)nwords + pre;
    if (total * 4u > pb_size || total > AIEN_GP_MAX_WORDS) return SUBMIT_LENGTH;
    if (put - retired >= OMEGA_GPU_AIEN_GP_ENTRIES - 1u) return SUBMIT_FULL;
    memset(plan, 0, sizeof *plan);
    if (pre) memcpy(plan->b, L2_INVAL_PREFIX, sizeof L2_INVAL_PREFIX);
    const uint64_t gp = omega_gpu_aien_gp_entry(pb_va, (uint32_t)total);
    const uint32_t slot = put % OMEGA_GPU_AIEN_GP_ENTRIES, gpput = (put + 1u) % OMEGA_GPU_AIEN_GP_ENTRIES, t32 = (uint32_t)total;
    memcpy(plan->b + PLAN_GP, &gp, 8); memcpy(plan->b + PLAN_SLOT, &slot, 4); memcpy(plan->b + PLAN_GPPUT, &gpput, 4);
    memcpy(plan->b + PLAN_PRE, &pre, 4); memcpy(plan->b + PLAN_TOTAL, &t32, 4);
    return SUBMIT_OK;
}
