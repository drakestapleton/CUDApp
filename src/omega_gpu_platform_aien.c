/* One AGPU request/reply block: the unit writes it by bytes, the module reads and answers it by struct. */
typedef union {
    uint8_t b[128];
    struct agpu_info info;
    struct agpu_mem_alloc alloc;
    struct agpu_mem_free free;
    struct agpu_chan_create chan;
    struct agpu_chan_destroy destroy;
} AienReq;
_Static_assert(sizeof(AienReq) == 128, "the unit's request block is 128 bytes");

/* Submission plan written into an AienReq by AG_SUBMIT: prefix words at 0, then these little-endian fields. */
#define PLAN_GP 24u    /* u64 GPFIFO entry */
#define PLAN_SLOT 32u  /* u32 ring slot */
#define PLAN_GPPUT 36u /* u32 new USERD GPPut */
#define PLAN_PRE 40u   /* u32 omega #457 prefix words */
#define PLAN_TOTAL 44u /* u32 words in the entry */
#define L2_INVAL_PREFIX_WORDS 5u

/* Operation numbers of native/aiengpu/context.om (m[0]); the unit's header comment gives each one's arguments. */
enum { AG_INFO = 1, AG_MEM_SIZE, AG_VA_START, AG_VA_ALIGN, AG_VA_TRY, AG_VA_BASE, AG_VA_TOP, AG_VA_STEP, AG_REQ_ALLOC,
       AG_RM_OK, AG_REQ_FREE, AG_REQ_CHAN, AG_REQ_DESTROY, AG_CACHE, AG_RANGE, AG_POLL, AG_SERIAL_GE, AG_SUBMIT,
       AG_GP_ENTRY };
enum { VA_TRY_RESERVE = 0, VA_TRY_STOP = 1, VA_TRY_WRAP = 2 };
enum { SUBMIT_OK = 0, SUBMIT_ARGS = 1, SUBMIT_LENGTH = 2, SUBMIT_FULL = 3 };
enum { POLL_OK = 0, POLL_RIGHTS = 1, POLL_ALIGN = 2, POLL_RANGE = 3 };

