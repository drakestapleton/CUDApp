/*
 * Verification oracle only; it is not linked into any product.
 * It prints Omega functions holding the NVIDIA 580.173.02 ABI values
 * that the fake RM in tests/share/fake-rm.om uses to decode requests.
 * The values come from the vendored headers through the C compiler, so
 * a literal in native/share/share.om that disagrees with them fails the
 * fixture instead of agreeing with itself.
 */
#include <stddef.h>
#include <stdio.h>
#include <sys/ioctl.h>

#include "nv-ioctl-numbers.h"
#include "nv-unix-nvos-params-wrappers.h"
#include "nv_escape.h"
#include "nvos.h"
#include "nvstatuscodes.h"
#include "rs_access.h"
#include "uvm_ioctl.h"

static void k(const char *name, unsigned long long value)
{
	printf("fn %s to ulong\nret %llu\nend\n", name, value);
}

#define REQ(nr, type) ((unsigned long long)_IOWR(NV_IOCTL_MAGIC, (nr), type))
#define OFF(type, field) ((unsigned long long)offsetof(type, field))

int main(void)
{
	printf("note SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception\n");
	printf("note Generated by tests/share/abi-oracle.c from third_party/nvidia-open-580.173.02.\n");
	k("kreqalloc", REQ(NV_ESC_RM_ALLOC, NVOS21_PARAMETERS));
	k("kreqfree", REQ(NV_ESC_RM_FREE, NVOS00_PARAMETERS));
	k("kreqdup", REQ(NV_ESC_RM_DUP_OBJECT, NVOS55_PARAMETERS));
	k("kreqshare", REQ(NV_ESC_RM_SHARE, NVOS57_PARAMETERS));
	k("kreqmap", REQ(NV_ESC_RM_MAP_MEMORY, nv_ioctl_nvos33_parameters_with_fd));
	k("kreqdma", REQ(NV_ESC_RM_MAP_MEMORY_DMA, NVOS46_PARAMETERS));
	k("krequndma", REQ(NV_ESC_RM_UNMAP_MEMORY_DMA, NVOS47_PARAMETERS));
	k("kszdup", sizeof(NVOS55_PARAMETERS));
	k("kszshare", sizeof(NVOS57_PARAMETERS));
	k("kszmap", sizeof(nv_ioctl_nvos33_parameters_with_fd));
	k("kszdma", sizeof(NVOS46_PARAMETERS));
	k("kszundma", sizeof(NVOS47_PARAMETERS));
	k("kszfree", sizeof(NVOS00_PARAMETERS));

	k("kalcclient", OFF(NVOS21_PARAMETERS, hRoot));
	k("kalcparent", OFF(NVOS21_PARAMETERS, hObjectParent));
	k("kalcnew", OFF(NVOS21_PARAMETERS, hObjectNew));
	k("kalcclass", OFF(NVOS21_PARAMETERS, hClass));
	k("kalcstatus", OFF(NVOS21_PARAMETERS, status));
	k("kmemsize", OFF(NV_MEMORY_ALLOCATION_PARAMS, size));
	k("kfreeclient", OFF(NVOS00_PARAMETERS, hRoot));
	k("kfreeparent", OFF(NVOS00_PARAMETERS, hObjectParent));
	k("kfreeobj", OFF(NVOS00_PARAMETERS, hObjectOld));
	k("kfreestatus", OFF(NVOS00_PARAMETERS, status));

	k("kdupclient", OFF(NVOS55_PARAMETERS, hClient));
	k("kdupparent", OFF(NVOS55_PARAMETERS, hParent));
	k("kdupobj", OFF(NVOS55_PARAMETERS, hObject));
	k("kdupsrcclient", OFF(NVOS55_PARAMETERS, hClientSrc));
	k("kdupsrcobj", OFF(NVOS55_PARAMETERS, hObjectSrc));
	k("kdupflags", OFF(NVOS55_PARAMETERS, flags));
	k("kdupstatus", OFF(NVOS55_PARAMETERS, status));
	k("kdupflagsnone", NV04_DUP_HANDLE_FLAGS_NONE);

	k("kshclient", OFF(NVOS57_PARAMETERS, hClient));
	k("kshobj", OFF(NVOS57_PARAMETERS, hObject));
	k("kshtarget", OFF(NVOS57_PARAMETERS, sharePolicy) + OFF(RS_SHARE_POLICY, target));
	k("kshmask", OFF(NVOS57_PARAMETERS, sharePolicy) + OFF(RS_SHARE_POLICY, accessMask));
	k("kshtype", OFF(NVOS57_PARAMETERS, sharePolicy) + OFF(RS_SHARE_POLICY, type));
	k("kshaction", OFF(NVOS57_PARAMETERS, sharePolicy) + OFF(RS_SHARE_POLICY, action));
	k("kshstatus", OFF(NVOS57_PARAMETERS, status));
	k("kshtoken", RS_SHARE_TYPE_OS_SECURITY_TOKEN);
	k("kshdupbit", 1ULL << RS_ACCESS_DUP_OBJECT);

	k("kmapclient", OFF(nv_ioctl_nvos33_parameters_with_fd, params.hClient));
	k("kmapdevice", OFF(nv_ioctl_nvos33_parameters_with_fd, params.hDevice));
	k("kmapmem", OFF(nv_ioctl_nvos33_parameters_with_fd, params.hMemory));
	k("kmapoffset", OFF(nv_ioctl_nvos33_parameters_with_fd, params.offset));
	k("kmaplength", OFF(nv_ioctl_nvos33_parameters_with_fd, params.length));
	k("kmapstatus", OFF(nv_ioctl_nvos33_parameters_with_fd, params.status));
	k("kmapflags", OFF(nv_ioctl_nvos33_parameters_with_fd, params.flags));
	k("kmapfd", OFF(nv_ioctl_nvos33_parameters_with_fd, fd));
	k("kmapro", NVOS33_FLAGS_ACCESS_READ_ONLY);

	k("kdmaclient", OFF(NVOS46_PARAMETERS, hClient));
	k("kdmadevice", OFF(NVOS46_PARAMETERS, hDevice));
	k("kdmactx", OFF(NVOS46_PARAMETERS, hDma));
	k("kdmamem", OFF(NVOS46_PARAMETERS, hMemory));
	k("kdmalength", OFF(NVOS46_PARAMETERS, length));
	k("kdmaflags", OFF(NVOS46_PARAMETERS, flags));
	k("kdmaoffset", OFF(NVOS46_PARAMETERS, dmaOffset));
	k("kdmastatus", OFF(NVOS46_PARAMETERS, status));
	k("kdmaro", NVOS46_FLAGS_ACCESS_READ_ONLY);
	k("kundmamem", OFF(NVOS47_PARAMETERS, hMemory));
	k("kundmastatus", OFF(NVOS47_PARAMETERS, status));

	k("kuvmrange", UVM_CREATE_EXTERNAL_RANGE);
	k("kuvmmapext", UVM_MAP_EXTERNAL_ALLOCATION);
	k("kuvmfree", UVM_FREE);
	k("kszrange", sizeof(UVM_CREATE_EXTERNAL_RANGE_PARAMS));
	k("kszmapext", sizeof(UVM_MAP_EXTERNAL_ALLOCATION_PARAMS));
	k("kszuvmfree", sizeof(UVM_FREE_PARAMS));
	k("krangebase", OFF(UVM_CREATE_EXTERNAL_RANGE_PARAMS, base));
	k("krangelength", OFF(UVM_CREATE_EXTERNAL_RANGE_PARAMS, length));
	k("krangestatus", OFF(UVM_CREATE_EXTERNAL_RANGE_PARAMS, rmStatus));
	k("kextbase", OFF(UVM_MAP_EXTERNAL_ALLOCATION_PARAMS, base));
	k("kextlength", OFF(UVM_MAP_EXTERNAL_ALLOCATION_PARAMS, length));
	k("kexttype", OFF(UVM_MAP_EXTERNAL_ALLOCATION_PARAMS, perGpuAttributes[0].gpuMappingType));
	k("kextuuid", OFF(UVM_MAP_EXTERNAL_ALLOCATION_PARAMS, perGpuAttributes[0].gpuUuid));
	k("kextcount", OFF(UVM_MAP_EXTERNAL_ALLOCATION_PARAMS, gpuAttributesCount));
	k("kextfd", OFF(UVM_MAP_EXTERNAL_ALLOCATION_PARAMS, rmCtrlFd));
	k("kextclient", OFF(UVM_MAP_EXTERNAL_ALLOCATION_PARAMS, hClient));
	k("kextmem", OFF(UVM_MAP_EXTERNAL_ALLOCATION_PARAMS, hMemory));
	k("kextstatus", OFF(UVM_MAP_EXTERNAL_ALLOCATION_PARAMS, rmStatus));
	k("kextro", UvmGpuMappingTypeReadOnly);
	k("kextrw", UvmGpuMappingTypeReadWriteAtomic);
	k("kfreebase", OFF(UVM_FREE_PARAMS, base));
	k("kfreestat", OFF(UVM_FREE_PARAMS, rmStatus));

	k("kerrperm", NV_ERR_INSUFFICIENT_PERMISSIONS);
	k("kerrbase", NV_ERR_INVALID_BASE);
	k("kerrlimit", NV_ERR_INVALID_LIMIT);
	k("kerrclient", NV_ERR_INVALID_CLIENT);
	k("kerrnotfound", NV_ERR_OBJECT_NOT_FOUND);
	return 0;
}
